// Explanation service. The UI depends only on the ExplanationService interface.
//
// Mode 1 (default, demo): deterministic local templates. No network, no model.
// Mode 2: if VITE_API_BASE_URL is set, try POST {base}/api/explain on YOUR backend.
//         If it is unreachable, slow, or returns something unexpected, fall back to Mode 1
//         and say so in the label. See docs/BACKEND_CONTRACT.md.
import { getConcept } from "@/data/concepts";
import { getConceptContent } from "@/data/conceptContent";
import { QUESTION_BY_ID } from "@/data/questions";
import { getBackendConfig } from "@/services/apiConfig";
import { getStoredSessionId } from "@/services/api";
import type { ConceptId, OptionKey } from "@/types";

export interface ExplanationEvidence {
  conceptId: ConceptId;
  questionIds?: number[] | undefined;
  /** The student's actual answers, so a backend can reason over real evidence. */
  answers?: Partial<Record<number, OptionKey>> | undefined;
}

export interface Explanation {
  label: string;
  title: string;
  paragraphs: string[];
  note: string;
  source: "template" | "backend" | "template-fallback";
}

export interface ExplanationService {
  getExplanation(evidence: ExplanationEvidence): Promise<Explanation>;
}

export const templateExplanationService: ExplanationService = {
  async getExplanation({ conceptId, questionIds = [] }) {
    const concept = getConcept(conceptId);
    const content = getConceptContent(conceptId);
    const paragraphs: string[] = [];
    if (content) {
      paragraphs.push(content.explanation[0] ?? "", `Key idea: ${content.formula}`);
    }
    const first = questionIds[0];
    const q = first !== undefined ? QUESTION_BY_ID[first] : undefined;
    if (q) {
      const why = Object.values(q.commonErrors)[0];
      if (why) paragraphs.push(`In Question ${q.id}, a common slip is: ${why}`);
    }
    if (content) paragraphs.push(`Try this: ${content.example.prompt}`);
    if (paragraphs.length === 0) {
      paragraphs.push(
        `${concept?.name ?? conceptId} has no pre-written lesson in demo mode. Connect the backend to generate an explanation from your own PDFs.`,
      );
    }
    return {
      label: "Demo explanation (template, not AI)",
      title: `Another way to see ${concept?.name ?? conceptId}`,
      paragraphs,
      note: "Live AI explanations appear when a model backend is connected.",
      source: "template",
    };
  },
};

function isBackendPayload(x: unknown): x is { title: string; paragraphs: string[]; note?: string } {
  if (typeof x !== "object" || x === null) return false;
  const o = x as Record<string, unknown>;
  return (
    typeof o["title"] === "string" &&
    Array.isArray(o["paragraphs"]) &&
    o["paragraphs"].length > 0 &&
    o["paragraphs"].every((p) => typeof p === "string") &&
    (o["note"] === undefined || typeof o["note"] === "string")
  );
}

const TIMEOUT_MS = 8000;

export const backendExplanationService: ExplanationService = {
  async getExplanation(evidence) {
    const { baseUrl } = getBackendConfig();
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), TIMEOUT_MS);
    try {
      const questionIds = evidence.questionIds ?? [];
      const sessionId = getStoredSessionId();
      const res = await fetch(`${baseUrl}/api/explain`, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          // Grounds the explanation in the session's documents when one exists.
          ...(sessionId ? { "X-Session-Id": sessionId } : {}),
        },
        signal: controller.signal,
        body: JSON.stringify({
          conceptId: evidence.conceptId,
          conceptName: getConcept(evidence.conceptId)?.name ?? evidence.conceptId,
          evidence: questionIds.flatMap((id) => {
            const q = QUESTION_BY_ID[id];
            const chosen = evidence.answers?.[id];
            if (!q || !chosen) return [];
            return [
              {
                questionId: id,
                prompt: q.prompt,
                chosen,
                correct: q.correct,
                pattern: q.commonErrors[chosen] ?? null,
              },
            ];
          }),
        }),
      });
      if (!res.ok) throw new Error(`Backend responded ${res.status}`);
      const data: unknown = await res.json();
      if (!isBackendPayload(data)) throw new Error("Unexpected response shape");
      return {
        label: "AI explanation (your backend)",
        title: data.title,
        paragraphs: data.paragraphs,
        note:
          data.note ??
          "Generated by the connected backend. Treat it as a hypothesis, not a verdict.",
        source: "backend",
      };
    } finally {
      clearTimeout(timer);
    }
  },
};

export const explanationService: ExplanationService = {
  async getExplanation(evidence) {
    if (!getBackendConfig().configured) return templateExplanationService.getExplanation(evidence);
    try {
      return await backendExplanationService.getExplanation(evidence);
    } catch {
      const fallback = await templateExplanationService.getExplanation(evidence);
      return {
        ...fallback,
        label: "Demo explanation (backend unavailable)",
        note: "The configured backend could not be reached, so this pre-written template is shown instead.",
        source: "template-fallback",
      };
    }
  },
};
