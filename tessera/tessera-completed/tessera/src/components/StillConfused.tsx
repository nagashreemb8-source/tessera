import { useEffect, useState } from "react";
import { HelpCircle } from "lucide-react";
import {
  Sheet,
  SheetContent,
  SheetDescription,
  SheetHeader,
  SheetTitle,
} from "@/components/ui/sheet";
import { explanationService, type Explanation } from "@/services/explanationService";
import { useTessera } from "@/state/AppState";
import type { ConceptId } from "@/types";

export function StillConfused({
  conceptId,
  questionIds,
}: {
  conceptId: ConceptId;
  questionIds?: number[] | undefined;
}) {
  const [open, setOpen] = useState(false);
  const [exp, setExp] = useState<Explanation | null>(null);
  const { state } = useTessera();
  const key = questionIds?.join(",");

  useEffect(() => {
    if (!open) return;
    let live = true;
    setExp(null);
    explanationService
      .getExplanation({ conceptId, questionIds, answers: state.answers })
      .then((e) => live && setExp(e))
      .catch(() => live && setExp(null));
    return () => {
      live = false;
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [open, conceptId, key]);

  return (
    <>
      <button type="button" className="btn btn-quiet" onClick={() => setOpen(true)}>
        <HelpCircle className="h-4 w-4" aria-hidden="true" /> Still confused?
      </button>
      <Sheet open={open} onOpenChange={setOpen}>
        <SheetContent className="w-full border-border bg-surface sm:max-w-md">
          <SheetHeader>
            <p className="eyebrow text-developing">{exp?.label ?? "Loading explanation"}</p>
            <SheetTitle className="font-display text-2xl font-medium">
              {exp?.title ?? "Loading…"}
            </SheetTitle>
            <SheetDescription>
              {exp?.source === "backend"
                ? "Generated by the connected backend."
                : "A pre-written explanation built from local templates."}
            </SheetDescription>
          </SheetHeader>
          <div className="mt-4 space-y-4 px-4 text-sm leading-relaxed">
            {exp
              ? exp.paragraphs.map((p, i) => <p key={i}>{p}</p>)
              : [1, 2, 3].map((i) => (
                  <div key={i} className="h-4 animate-pulse rounded bg-surface-2" />
                ))}
            {exp && <p className="panel-raised p-3 text-xs text-muted-foreground">{exp.note}</p>}
          </div>
        </SheetContent>
      </Sheet>
    </>
  );
}
